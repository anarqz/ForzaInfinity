#!/usr/bin/env python3
"""Writes hook/adapters/azimuth_font_widths.h: the advance of each glyph of the game's Anthem_A font
(media/ui/Fonts.zip Anthem_A.vfont), for centring the INFINITY status lines on the pause menu.

The .vfont holds, from offset 0xc0, 28-byte glyph records: u32 codepoint, f32 advance (em), ...
Usage: tools/font_widths.py <Mount folder> > hook/adapters/azimuth_font_widths.h"""
import struct, sys, zipfile, pathlib

mount = pathlib.Path(sys.argv[1])
data = zipfile.ZipFile(mount / "media" / "ui" / "Fonts.zip").read("Anthem_A.vfont")
glyphs = {}
at = 0xC0
while at + 28 <= len(data):
    cp, adv = struct.unpack_from("<If", data, at)
    if not (0 <= cp < 0x10000 and 0 <= adv < 3):
        break
    glyphs[cp] = adv
    at += 28
rows = sorted(glyphs.items())
print("/* Generated by tools/font_widths.py from the game's Anthem_A.vfont: each glyph's advance, in")
print("   thousandths of an em (%d glyphs). */" % len(rows))
print("static const struct {")
print("    unsigned short codepoint, advance;")
print("} azimuth_font_widths[] = {")
line = "   "
for cp, adv in rows:
    item = " {0x%x, %d}," % (cp, round(adv * 1000))
    if len(line) + len(item) > 110:
        print(line)
        line = "   "
    line += item
print(line)
print("};")
