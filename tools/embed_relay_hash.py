#!/usr/bin/env python3
"""Writes hook/adapters/azimuth_relay_hash.h: the SHA-256 of the dedicated_server.exe released
with this hook.

A hook that updated itself (azimuth_update.c) fetches that dedicated_server.exe from its own
release when data/bin has another one or none, and installs it only when it matches this hash
and its signature verifies. tools/package_release.sh runs this after building the relay and
before building the hook.

    tools/embed_relay_hash.py <dedicated_server.exe>
"""
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "hook" / "adapters" / "azimuth_relay_hash.h"


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    digest = hashlib.sha256(Path(sys.argv[1]).read_bytes()).hexdigest()
    text = (
        "/* Generated by tools/embed_relay_hash.py (tools/package_release.sh): the SHA-256 of the\r\n"
        "   dedicated_server.exe released with this hook (azimuth_update.c). */\r\n"
        "#ifndef AZIMUTH_RELAY_HASH_H\r\n"
        "#define AZIMUTH_RELAY_HASH_H\r\n"
        f'#define AZIMUTH_RELAY_SHA256 "{digest}"\r\n'
        "#endif\r\n"
    )
    HEADER.write_bytes(text.encode("ascii"))
    print(HEADER)


if __name__ == "__main__":
    main()
