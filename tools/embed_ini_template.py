#!/usr/bin/env python3
"""Writes hook/adapters/azimuth_ini_template.h from release/FH2_ExtraOptions.template.ini.

The hook writes that template when a player has no FH2_ExtraOptions.ini (a DLL copied by hand,
an INI deleted), so the two must not drift: tools/package_release.sh runs this before building.

    tools/embed_ini_template.py [--server https://host|host:port]   (default: the public server)
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / "release" / "FH2_ExtraOptions.template.ini"
HEADER = ROOT / "hook" / "adapters" / "azimuth_ini_template.h"
PUBLIC_SERVER = "https://infinity.anarqz.dev"


def c_string(line):
    return '"' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\r\\n"'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--server", default=PUBLIC_SERVER)
    server = parser.parse_args().server
    text = TEMPLATE.read_bytes().decode("ascii")
    if "__SERVER__" not in text:
        raise SystemExit(f"{TEMPLATE}: no Server=__SERVER__ line")
    lines = text.replace("\r\n", "\n").rstrip("\n").split("\n")
    out = [
        "/* Generated by tools/embed_ini_template.py (ForzaInfinity monorepo) from",
        "   release/FH2_ExtraOptions.template.ini: do not edit, run the script after changing the template. */",
        "#ifndef AZIMUTH_INI_TEMPLATE_H",
        "#define AZIMUTH_INI_TEMPLATE_H",
        "",
        "/* The server a missing [Network] Server gets. */",
        f'#define AZIMUTH_INI_SERVER "{server}"',
        "",
        "/* FH2_ExtraOptions.ini for a player who has none. */",
        "static const char azimuth_ini_template[] =",
    ]
    out += ["    " + c_string(line.replace("__SERVER__", server)) for line in lines]
    out[-1] += ";"
    out += ["", "#endif", ""]
    HEADER.write_bytes("\r\n".join(out).encode("ascii"))
    print(HEADER)


if __name__ == "__main__":
    main()
